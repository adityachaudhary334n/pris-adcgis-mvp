#!/usr/bin/env python3
"""Merge district profile JSON files -> data/clean/district_info_load.sql (idempotent upsert) + report.

Inputs : data/districts/up_75_districts_profile.json  (+ data/districts/extra/*.json, same shape, merged in name order)
         data/clean/up_hierarchy.json                 (district ids, produced by build_up_admin.py)
Output : data/clean/district_info_load.sql, data/clean/district_info_report.json
"""
import collections, glob, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[1]
ALIAS = {"kushinagar": "kushinagar", "lakhimpurkheri": "kheri", "santkabirnagar": "santkabeernagar", "siddharthnagar": "siddharthnagar"}
GENERIC_MIN = 10  # a value repeated verbatim in >= 10 districts is boilerplate, not district knowledge
norm = lambda s: re.sub(r"[^a-z]", "", s.lower())


def deep_merge(a, b):
    for k, v in b.items():
        if isinstance(v, dict) and isinstance(a.get(k), dict):
            deep_merge(a[k], v)
        else:
            a[k] = v
    return a


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    base = json.load(open(ROOT / "data/districts/up_75_districts_profile.json", encoding="utf-8"))
    for f in sorted(glob.glob(str(ROOT / "data/districts/extra/*.json"))):
        deep_merge(base, json.load(open(f, encoding="utf-8")))
    hier = json.load(open(ROOT / "data/clean/up_hierarchy.json", encoding="utf-8"))["districts"]
    ids = {norm(d["name"]): d for d in hier}
    matched, unmatched = {}, []
    for name in base:
        k = norm(name); k = ALIAS.get(k, k)
        (matched.__setitem__(name, ids[k]) if k in ids else unmatched.append(name))
    missing_in_file = sorted(d["name"] for d in hier if d["name"] not in {m["name"] for m in matched.values()})

    SKIP = {"district", "division", "metadata_source"}
    cnt = collections.defaultdict(collections.Counter)
    for name, v in base.items():
        for sec, fields in v.items():
            if sec in SKIP or not isinstance(fields, dict): continue
            for k, x in fields.items(): cnt[(sec, k)][json.dumps(x, sort_keys=True, ensure_ascii=False)] += 1
    generic = {key for key, c in cnt.items() if c.most_common(1)[0][1] >= GENERIC_MIN}

    sql = ["-- GENERATED by scripts/build_district_info.py (safe to re-run on a live database).",
           "CREATE TABLE IF NOT EXISTS district_info (\n  unit_id UUID PRIMARY KEY REFERENCES admin_boundaries(id) ON DELETE CASCADE,\n  district VARCHAR(120) NOT NULL, division VARCHAR(120), source TEXT,\n"
           "  sections JSONB NOT NULL DEFAULT '{}', generic JSONB NOT NULL DEFAULT '[]', updated_at TIMESTAMPTZ DEFAULT NOW());"]
    for name, d in matched.items():
        v = base[name]
        sections = {s: f for s, f in v.items() if s not in SKIP and isinstance(f, dict)}
        gen = sorted(f"{s}.{k}" for s, f in sections.items() for k in f if (s, k) in generic)
        sql.append("INSERT INTO district_info (unit_id, district, division, source, sections, generic) VALUES "
                   f"({q(d['id'])}, {q(d['name'])}, {q(v.get('division'))}, {q(v.get('metadata_source'))}, {q(json.dumps(sections, ensure_ascii=False))}::jsonb, {q(json.dumps(gen))}::jsonb) "
                   "ON CONFLICT (unit_id) DO UPDATE SET district = EXCLUDED.district, division = EXCLUDED.division, source = EXCLUDED.source, "
                   "sections = EXCLUDED.sections, generic = EXCLUDED.generic, updated_at = NOW();")
    (ROOT / "data/clean/district_info_load.sql").write_text("\n".join(sql) + "\n", encoding="utf-8")
    rep = {"districts_loaded": len(matched), "unmatched_in_file": unmatched, "database_districts_without_profile": missing_in_file,
           "generic_fields (same text in >= %d districts - replace with district-specific facts)" % GENERIC_MIN: sorted(f"{s}.{k}" for s, k in generic),
           "district_specific_fields": sorted(f"{s}.{k}" for (s, k) in cnt if (s, k) not in generic),
           "population_sum": sum(v.get("demography", {}).get("population_2011", 0) for v in base.values()),
           "note": "Census 2011 UP total is 199,812,341; a larger sum means some post-2011 districts (Amethi, Hapur, Sambhal, Shamli, Kasganj, Bhadohi...) probably still carry their parent district's population."}
    json.dump(rep, open(ROOT / "data/clean/district_info_report.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(rep, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
